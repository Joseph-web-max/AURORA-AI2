"""AURORA AI FastAPI backend.

Database: PostgreSQL (Supabase Session Pooler recommended) or SQLite for local tests.
AI inference: OpenAI-compatible endpoint configured through Render environment variables.
"""

import hashlib
import hmac
import os
import secrets
import time
from typing import Optional

import httpx
import jwt
from fastapi import Depends, FastAPI, Header, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, EmailStr, Field
from sqlalchemy import create_engine, text
from sqlalchemy.engine import make_url
from sqlalchemy.exc import IntegrityError, SQLAlchemyError

APP_NAME = "AURORA AI Backend"

# Set a persistent, randomly generated JWT_SECRET in Render. Changing it invalidates
# previously issued sessions, so do not rotate it casually.
JWT_SECRET = os.getenv("JWT_SECRET")
if not JWT_SECRET:
    JWT_SECRET = secrets.token_urlsafe(48)
    if os.getenv("RENDER"):
        raise RuntimeError("JWT_SECRET is required in the Render environment")


def build_database_url() -> str:
    raw_url = os.getenv("DATABASE_URL", "sqlite:///./aurora.db").strip()
    if not raw_url:
        raise RuntimeError("DATABASE_URL is empty")

    if raw_url.startswith("postgres://"):
        raw_url = raw_url.replace("postgres://", "postgresql://", 1)

    if raw_url.startswith("postgresql://") or raw_url.startswith("postgresql+psycopg://"):
        # Explicitly use Psycopg 3, which is installed by requirements.txt.
        url = make_url(raw_url)
        url = url.set(drivername="postgresql+psycopg")
        # Supabase requires TLS. This is also safe for its Session Pooler.
        query = dict(url.query)
        query.setdefault("sslmode", "require")
        url = url.set(query=query)
        return url.render_as_string(hide_password=False)

    if raw_url.startswith("sqlite:"):
        return raw_url

    raise RuntimeError(
        "Unsupported DATABASE_URL. Use the Supabase PostgreSQL Session Pooler URI."
    )


DATABASE_URL = build_database_url()
engine_kwargs = {"pool_pre_ping": True, "pool_recycle": 300}
if DATABASE_URL.startswith("sqlite:"):
    engine_kwargs["connect_args"] = {"check_same_thread": False}
engine = create_engine(DATABASE_URL, **engine_kwargs)

app = FastAPI(title=APP_NAME, version="0.3.0")

allowed_origins = [
    origin.strip()
    for origin in os.getenv("AURORA_ALLOWED_ORIGINS", "*").split(",")
    if origin.strip()
]
app.add_middleware(
    CORSMiddleware,
    allow_origins=allowed_origins or ["*"],
    allow_credentials=False,
    allow_methods=["GET", "POST", "OPTIONS"],
    allow_headers=["Authorization", "Content-Type"],
)


def init_db() -> None:
    """Create the application users table using PostgreSQL- or SQLite-compatible DDL."""
    if engine.dialect.name == "postgresql":
        ddl = """
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email VARCHAR(320) NOT NULL UNIQUE,
                username VARCHAR(40) NOT NULL UNIQUE,
                full_name VARCHAR(100) NOT NULL DEFAULT '',
                password_hash TEXT NOT NULL,
                created_at BIGINT NOT NULL
            )
        """
    elif engine.dialect.name == "sqlite":
        ddl = """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                email TEXT NOT NULL UNIQUE,
                username TEXT NOT NULL UNIQUE,
                full_name TEXT NOT NULL DEFAULT '',
                password_hash TEXT NOT NULL,
                created_at INTEGER NOT NULL
            )
        """
    else:
        raise RuntimeError(f"Unsupported database dialect: {engine.dialect.name}")

    with engine.begin() as connection:
        connection.execute(text(ddl))


@app.on_event("startup")
def startup_event() -> None:
    try:
        init_db()
        print(f"{APP_NAME}: database schema is ready ({engine.dialect.name})")
    except SQLAlchemyError as exc:
        # Render logs get the diagnostic; API responses do not expose credentials.
        print(f"AURORA database initialization failed: {type(exc).__name__}: {exc}")
        raise


class RegisterIn(BaseModel):
    email: EmailStr
    username: str = Field(min_length=3, max_length=40)
    name: Optional[str] = Field(default="", max_length=100)
    full_name: Optional[str] = Field(default="", max_length=100)
    password: str = Field(min_length=8, max_length=200)


class LoginIn(BaseModel):
    email: Optional[str] = None
    username: Optional[str] = None
    password: str


class ChatMessage(BaseModel):
    role: str
    content: str


class ChatIn(BaseModel):
    model: str = "aurora"
    messages: list[ChatMessage]
    stream: bool = False
    max_tokens: Optional[int] = 1024
    temperature: Optional[float] = 0.7


def password_hash(password: str, salt: Optional[bytes] = None) -> str:
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode("utf-8"), salt=salt, n=2**14, r=8, p=1)
    return salt.hex() + "$" + digest.hex()


def password_verify(password: str, stored: str) -> bool:
    try:
        salt_hex, digest_hex = stored.split("$", 1)
        expected = bytes.fromhex(digest_hex)
        actual = hashlib.scrypt(
            password.encode("utf-8"), salt=bytes.fromhex(salt_hex), n=2**14, r=8, p=1
        )
        return hmac.compare_digest(actual, expected)
    except (ValueError, TypeError):
        return False


def issue_token(user_id: int, email: str) -> str:
    now = int(time.time())
    return jwt.encode(
        {
            "sub": str(user_id),
            "email": email,
            "iat": now,
            "exp": now + 60 * 60 * 24 * 7,
        },
        JWT_SECRET,
        algorithm="HS256",
    )


def current_user(authorization: Optional[str] = Header(default=None)):
    if not authorization or not authorization.lower().startswith("bearer "):
        raise HTTPException(status_code=401, detail="Sign in required")
    token = authorization.split(" ", 1)[1].strip()
    try:
        payload = jwt.decode(token, JWT_SECRET, algorithms=["HS256"])
        return {"id": int(payload["sub"]), "email": payload["email"]}
    except (jwt.PyJWTError, KeyError, TypeError, ValueError):
        raise HTTPException(status_code=401, detail="Invalid or expired session")


@app.get("/")
def root():
    return {"name": APP_NAME, "status": "online", "docs": "/docs"}


@app.get("/health")
def health():
    try:
        with engine.connect() as connection:
            connection.execute(text("SELECT 1"))
        return {
            "status": "healthy",
            "service": APP_NAME,
            "database": "connected",
            "database_provider": engine.dialect.name,
            "inference_configured": bool(
                os.getenv("AURORA_MODEL_BASE_URL") and os.getenv("AURORA_MODEL_NAME")
            ),
        }
    except SQLAlchemyError as exc:
        print(f"AURORA health database check failed: {type(exc).__name__}: {exc}")
        raise HTTPException(status_code=503, detail="Database unavailable")


@app.post("/auth/register")
@app.post("/api/auth/register")
@app.post("/api/v1/auth/register")
@app.post("/auth/signup")
@app.post("/register")
@app.post("/signup")
def register(data: RegisterIn):
    email = str(data.email).lower().strip()
    username = data.username.lower().strip()
    if not username.replace("_", "").replace("-", "").isalnum():
        raise HTTPException(
            status_code=400,
            detail="Username may contain letters, numbers, underscores and hyphens only",
        )

    params = {
        "email": email,
        "username": username,
        "full_name": (data.full_name or data.name or "").strip(),
        "password_hash": password_hash(data.password),
        "created_at": int(time.time()),
    }
    try:
        with engine.begin() as connection:
            result = connection.execute(
                text("""
                    INSERT INTO users
                        (email, username, full_name, password_hash, created_at)
                    VALUES
                        (:email, :username, :full_name, :password_hash, :created_at)
                    RETURNING id
                """),
                params,
            )
            user_id = result.scalar_one()
    except IntegrityError:
        raise HTTPException(
            status_code=409, detail="That email or username is already registered"
        )
    except SQLAlchemyError as exc:
        print(f"AURORA registration database error: {type(exc).__name__}: {exc}")
        raise HTTPException(status_code=500, detail="Account registration failed")

    token = issue_token(int(user_id), email)
    return {
        "access_token": token,
        "token_type": "bearer",
        "user": {"id": int(user_id), "email": email, "username": username},
    }


@app.post("/auth/login")
@app.post("/api/auth/login")
@app.post("/api/v1/auth/login")
@app.post("/auth/token")
@app.post("/login")
@app.post("/token")
def login(data: LoginIn):
    identity = (data.email or data.username or "").lower().strip()
    if not identity:
        raise HTTPException(status_code=400, detail="Enter your email or username")

    try:
        with engine.connect() as connection:
            user = connection.execute(
                text("""
                    SELECT id, email, username, password_hash FROM users
                    WHERE lower(email) = :identity OR lower(username) = :identity
                """),
                {"identity": identity},
            ).mappings().first()
    except SQLAlchemyError as exc:
        print(f"AURORA login database error: {type(exc).__name__}: {exc}")
        raise HTTPException(status_code=500, detail="Login service unavailable")

    if not user or not password_verify(data.password, user["password_hash"]):
        raise HTTPException(status_code=401, detail="Incorrect email/username or password")

    token = issue_token(int(user["id"]), user["email"])
    return {
        "access_token": token,
        "token_type": "bearer",
        "user": {"id": user["id"], "email": user["email"], "username": user["username"]},
    }


def inference_config():
    return (
        os.getenv("AURORA_MODEL_BASE_URL", "").rstrip("/"),
        os.getenv("AURORA_MODEL_API_KEY", ""),
        os.getenv("AURORA_MODEL_NAME", ""),
    )


@app.get("/ai/native/models")
def native_models(user=Depends(current_user)):
    base, key, model = inference_config()
    if not base or not model:
        raise HTTPException(status_code=503, detail="AURORA inference engine is not configured yet")

    headers = {"Authorization": f"Bearer {key}"} if key else {}
    try:
        with httpx.Client(timeout=30) as client:
            response = client.get(base + "/models", headers=headers)
            response.raise_for_status()
            payload = response.json()
        items = payload.get("data", payload.get("models", []))
        if not items:
            items = [{"id": model, "object": "model"}]
        return {"object": "list", "data": items}
    except httpx.HTTPStatusError as exc:
        raise HTTPException(
            status_code=502,
            detail=f"Model service error {exc.response.status_code}: {exc.response.text[:300]}",
        )
    except (httpx.HTTPError, ValueError) as exc:
        raise HTTPException(status_code=502, detail=f"Model service unavailable: {str(exc)[:250]}")


@app.post("/ai/native/chat/completions")
def native_chat(data: ChatIn, user=Depends(current_user)):
    base, key, model = inference_config()
    if not base or not model:
        raise HTTPException(status_code=503, detail="AURORA inference engine is not configured yet")

    headers = {"Content-Type": "application/json"}
    if key:
        headers["Authorization"] = f"Bearer {key}"
    payload = data.model_dump()
    payload["model"] = model
    payload["stream"] = False

    try:
        with httpx.Client(timeout=180) as client:
            response = client.post(base + "/chat/completions", headers=headers, json=payload)
            response.raise_for_status()
            return response.json()
    except httpx.HTTPStatusError as exc:
        raise HTTPException(
            status_code=502,
            detail=f"Inference error {exc.response.status_code}: {exc.response.text[:400]}",
        )
    except (httpx.HTTPError, ValueError) as exc:
        raise HTTPException(status_code=502, detail=f"Inference service unavailable: {str(exc)[:250]}")
